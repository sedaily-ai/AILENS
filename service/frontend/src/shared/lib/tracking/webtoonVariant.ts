/** 웹툰 표시 방식 구분(독자 지표 계측용). 스타일 전환 전·후를 GA4에서 비교하려면 이벤트마다 어느 방식인지 실려야 한다.
 *  v2 = 웹툰식 말풍선(타원·위쪽 여백·나레이션 띠) + 마지막 "핵심 정리" 카드가 붙은 글, v1 = 그 이전 방식.
 *  별도 필드를 만들지 않고 카드 이미지의 캡션("핵심 정리")으로 구분한다(파이프라인이 카드에 그 캡션을 붙인다). */
export function webtoonVariant(cuts: { caption?: string }[] | null | undefined): 'v1' | 'v2' {
  return (cuts ?? []).some((c) => c.caption === '핵심 정리') ? 'v2' : 'v1';
}
